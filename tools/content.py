# artikel mendalam yang sudah ada di situs: rentang bab -> halaman
def deep(n):
    if 10<=n<=16: return ["#/falak/komponen","Komponen &amp; Istilah Dasar (deklinasi, perata waktu)"]
    if 17<=n<=27: return ["#/falak/kiblat","Arah Kiblat: rumus, metode, sejarah, kasus"]
    if 28<=n<=40: return ["#/falak/shalat","Waktu Shalat: kriteria, rumus, kasus"]
    if 41<=n<=49: return ["#/falak/hilal","Awal Bulan Qomariyah: konsep, kriteria, kasus"]
    if 50<=n<=56: return ["#/falak/gerhana","Gerhana: syarat, siklus Saros, ibadah, kasus"]
    if n in (1,2,3,77,78): return ["#/falak","Ilmu Falak: pengantar dan sejarah ringkas"]
    if n==8: return ["#/cabang/mekanika-langit","Mekanika Langit"]
    if n in (71,74): return ["#/cabang/astrofisika","Astrofisika &amp; Fisika Bintang"]
    if n in (72,73): return ["#/cabang/planetologi","Ilmu Planet &amp; Eksoplanet"]
    return None

